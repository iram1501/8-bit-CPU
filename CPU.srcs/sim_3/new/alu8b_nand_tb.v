`timescale 1ns / 1ps

module alu8b_nand_tb;

    reg  [7:0] a, b;
    reg  [3:0] alu_op;

    wire [7:0] y;
    wire z, n, v, c;

    integer tests;
    integer errors;

    alu8b_nand uut (
        .a(a),
        .b(b),
        .alu_op(alu_op),
        .y(y),
        .z(z),
        .n(n),
        .v(v),
        .c(c)
    );

    task check;
        input [7:0] expected_y;
        input expected_z;
        input expected_n;
        input expected_c;
        input expected_v;

        begin
            #5;
            tests = tests + 1;

            if ((y === expected_y) &&
                (z === expected_z) &&
                (n === expected_n) &&
                (c === expected_c) &&
                (v === expected_v)) begin

                $display("PASS | op=%b | a=%b b=%b | y=%b | Z=%b N=%b C=%b V=%b",
                         alu_op, a, b, y, z, n, c, v);

            end
            else begin
                errors = errors + 1;

                $display("FAIL | op=%b | a=%b b=%b",
                         alu_op, a, b);

                $display("       Got:      y=%b Z=%b N=%b C=%b V=%b",
                         y, z, n, c, v);

                $display("       Expected: y=%b Z=%b N=%b C=%b V=%b",
                         expected_y,
                         expected_z,
                         expected_n,
                         expected_c,
                         expected_v);
            end
        end
    endtask


    initial begin

        tests  = 0;
        errors = 0;

        a = 0;
        b = 0;
        alu_op = 0;

        #10;


        // =====================================================
        // 0000 ADD
        // =====================================================

        // 5 + 3 = 8
        a = 8'd5;
        b = 8'd3;
        alu_op = 4'b0000;
        check(8'd8, 0, 0, 0, 0);

        // 127 + 1 = -128 -> signed overflow
        a = 8'b01111111;
        b = 8'b00000001;
        alu_op = 4'b0000;
        check(8'b10000000, 0, 1, 0, 1);

        // 255 + 1 = 0 with carry
        a = 8'b11111111;
        b = 8'b00000001;
        alu_op = 4'b0000;
        check(8'b00000000, 1, 0, 1, 0);


        // =====================================================
        // 0001 SUB
        // =====================================================

        // 5 - 3 = 2
        a = 8'd5;
        b = 8'd3;
        alu_op = 4'b0001;
        check(8'd2, 0, 0, 0, 0);

        // 3 - 5 = -2, borrow = 1
        a = 8'd3;
        b = 8'd5;
        alu_op = 4'b0001;
        check(8'b11111110, 0, 1, 1, 0);

        // -128 - 1 = 127 -> signed overflow
        a = 8'b10000000;
        b = 8'b00000001;
        alu_op = 4'b0001;
        check(8'b01111111, 0, 0, 0, 1);


        // =====================================================
        // 0010 AND
        // =====================================================

        a = 8'b11001100;
        b = 8'b10101010;
        alu_op = 4'b0010;
        check(8'b10001000, 0, 1, 0, 0);


        // =====================================================
        // 0011 OR
        // =====================================================

        a = 8'b11000000;
        b = 8'b00111100;
        alu_op = 4'b0011;
        check(8'b11111100, 0, 1, 0, 0);


        // =====================================================
        // 0100 XOR
        // =====================================================

        a = 8'b10101010;
        b = 8'b10101010;
        alu_op = 4'b0100;
        check(8'b00000000, 1, 0, 0, 0);


        // =====================================================
        // 0101 NOT A
        // =====================================================

        a = 8'b00001111;
        b = 0;
        alu_op = 4'b0101;
        check(8'b11110000, 0, 1, 0, 0);


        // =====================================================
        // 0110 SHIFT LEFT
        // =====================================================

        a = 8'b00110101;
        b = 0;
        alu_op = 4'b0110;
        check(8'b01101010, 0, 0, 0, 0);


        // =====================================================
        // 0111 SHIFT RIGHT
        // Assumes LOGICAL right shift
        // =====================================================

        a = 8'b10110100;
        b = 0;
        alu_op = 4'b0111;
        check(8'b01011010, 0, 0, 0, 0);


        // =====================================================
        // 1000 NAND
        // =====================================================

        a = 8'b11110000;
        b = 8'b11001100;
        alu_op = 4'b1000;
        check(8'b00111111, 0, 0, 0, 0);


        // =====================================================
        // 1001 NOR
        // =====================================================

        a = 8'b11110000;
        b = 8'b00001111;
        alu_op = 4'b1001;
        check(8'b00000000, 1, 0, 0, 0);


        // =====================================================
        // 1010 XNOR
        // =====================================================

        a = 8'b10101010;
        b = 8'b01010101;
        alu_op = 4'b1010;
        check(8'b00000000, 1, 0, 0, 0);


        // =====================================================
        // 1011 INC
        // =====================================================

        // 5 + 1 = 6
        a = 8'd5;
        b = 0;
        alu_op = 4'b1011;
        check(8'd6, 0, 0, 0, 0);

        // 127 + 1 = -128 -> overflow
        a = 8'b01111111;
        b = 0;
        alu_op = 4'b1011;
        check(8'b10000000, 0, 1, 0, 1);

        // 255 + 1 = 0 -> carry
        a = 8'b11111111;
        b = 0;
        alu_op = 4'b1011;
        check(8'b00000000, 1, 0, 1, 0);


        // =====================================================
        // 1100 DEC
        // =====================================================

        // 5 - 1 = 4
        a = 8'd5;
        b = 0;
        alu_op = 4'b1100;
        check(8'd4, 0, 0, 0, 0);

        // 0 - 1 = -1 -> borrow
        a = 8'b00000000;
        b = 0;
        alu_op = 4'b1100;
        check(8'b11111111, 0, 1, 1, 0);

        // -128 - 1 = 127 -> overflow
        a = 8'b10000000;
        b = 0;
        alu_op = 4'b1100;
        check(8'b01111111, 0, 0, 0, 1);


        // =====================================================
        // 1101 PASS A
        // =====================================================

        a = 8'b10100101;
        b = 8'b01011010;
        alu_op = 4'b1101;
        check(8'b10100101, 0, 1, 0, 0);


        // =====================================================
        // 1110 PASS B
        // =====================================================

        a = 8'b10100101;
        b = 8'b01011010;
        alu_op = 4'b1110;
        check(8'b01011010, 0, 0, 0, 0);


        // =====================================================
        // 1111 NEG A
        // =====================================================

        // -5
        a = 8'b00000101;
        b = 0;
        alu_op = 4'b1111;
        check(8'b11111011, 0, 1, 0, 0);

        // -(-1) = +1
        a = 8'b11111111;
        b = 0;
        alu_op = 4'b1111;
        check(8'b00000001, 0, 0, 0, 0);


        // =====================================================
        // SUMMARY
        // =====================================================

        $display("");
        $display("==========================================");

        if (errors == 0)
            $display("ALL TESTS PASSED: %0d/%0d", tests, tests);
        else
            $display("TESTS FAILED: %0d passed, %0d failed",
                     tests - errors, errors);

        $display("==========================================");

        $finish;

    end

endmodule